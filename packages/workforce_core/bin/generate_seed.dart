/// Writes the Supabase seed for the sample arena.
///
///     dart run bin/generate_seed.dart [output.sql] [--now=2026-11-04T23:30:00Z] [--seed=42]
///
/// The default output is `supabase/seed/sample_arena.sql` at the repository root.
///
/// Each table is loaded with
/// `insert into public.<t> (<cols>) select <cols> from jsonb_populate_recordset(null::public.<t>, $json$[...]$json$::jsonb)`
/// in batches of up to 1000 rows, all inside one transaction. Listing the columns lets columns
/// the entities do not carry (created_at, updated_at, contact_email, ...) take their defaults.
library;

import 'dart:convert';
import 'dart:io';

import 'package:workforce_core/src/sample/sample_arena.dart';

const _defaultNow = '2026-11-04T23:30:00Z';
const _batchSize = 1000;

void main(List<String> args) {
  var nowArg = _defaultNow;
  var seed = 42;
  String? outPath;
  for (final a in args) {
    if (a.startsWith('--now=')) {
      nowArg = a.substring(6);
    } else if (a.startsWith('--seed=')) {
      seed = int.parse(a.substring(7));
    } else if (a == '-h' || a == '--help') {
      stdout.writeln('usage: dart run bin/generate_seed.dart [output.sql] [--now=$_defaultNow] [--seed=42]');
      return;
    } else if (a.startsWith('--')) {
      stderr.writeln('Unknown option $a');
      exitCode = 64;
      return;
    } else {
      outPath = a;
    }
  }

  final now = DateTime.parse(nowArg).toUtc();
  final arena = SampleArena.generate(now: now, seed: seed);
  final out = File(outPath ?? _packageRoot().uri.resolve('../../supabase/seed/sample_arena.sql').toFilePath());
  out.parent.createSync(recursive: true);

  final sql = StringBuffer()
    ..writeln('-- Sample data for Pecan Valley Arena (fictional). Generated by')
    ..writeln('-- packages/workforce_core/bin/generate_seed.dart --now=${now.toIso8601String()} --seed=$seed')
    ..writeln('-- Do not edit by hand; regenerate instead.')
    ..writeln()
    ..writeln('begin;')
    ..writeln();
  final counts = <String, int>{};
  arena.toTables().forEach((table, rows) {
    counts[table] = rows.length;
    for (var i = 0; i < rows.length; i += _batchSize) {
      final batch = rows.sublist(i, i + _batchSize > rows.length ? rows.length : i + _batchSize);
      // Name the columns so the ones the JSON leaves out (created_at, ...) take their defaults.
      final columns = <String>{for (final r in batch) ...r.keys}.map((c) => '"$c"').join(', ');
      sql
        ..writeln('insert into public.$table ($columns)')
        ..writeln('select $columns from jsonb_populate_recordset(null::public.$table, \$json\$[')
        ..writeln(batch.map(jsonEncode).join(',\n'))
        ..writeln(']\$json\$::jsonb);')
        ..writeln();
    }
  });
  sql.writeln('commit;');

  final text = sql.toString();
  if (RegExp(r'\$json\$').allMatches(text).length != 2 * _statementCount(counts)) {
    stderr.writeln('Row data contains the dollar-quote tag; refusing to write.');
    exitCode = 1;
    return;
  }
  out.writeAsStringSync(text);
  stdout.writeln('Wrote ${out.absolute.path} (${text.length} bytes)');
  counts.forEach((table, n) => stdout.writeln('  ${table.padRight(28)} $n'));
}

int _statementCount(Map<String, int> counts) => counts.values.fold(0, (s, n) => s + (n + _batchSize - 1) ~/ _batchSize);

/// The package directory: next to this script's `bin/`, else the working directory.
Directory _packageRoot() {
  final script = File.fromUri(Platform.script);
  final candidate = script.parent.parent;
  if (File('${candidate.path}/pubspec.yaml').existsSync()) return candidate;
  return Directory.current;
}
